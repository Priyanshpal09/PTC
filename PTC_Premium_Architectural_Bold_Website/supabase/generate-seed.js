/* ============================================================
   PTC — seed generator

   Turns the content in PTC_Premium_Website/data.js into SQL that the
   Supabase SQL Editor can run. Re-run it whenever the baseline content
   changes:

     node supabase/generate-seed.js

   Writes supabase/seed.sql (data only) and supabase/setup.sql
   (schema.sql + the data), both idempotent: the seed only inserts into
   empty tables, so re-running it can never duplicate or overwrite rows.
   ============================================================ */

'use strict';

const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const website = path.join(root, 'PTC_Premium_Website');

/* data.js is a plain browser script that hangs everything off window.PTC */
const window = {};
new Function('window', fs.readFileSync(path.join(website, 'data.js'), 'utf8'))(window);

const PTC = window.PTC || {};
const projects = PTC.projects || [];
const indexEntries = PTC.indexEntries || [];
const gallery = PTC.gallery || [];

function q(value) {
  if (value === null || value === undefined) return 'null';
  return "'" + String(value).replace(/'/g, "''") + "'";
}

function valuesBlock(rows, width) {
  return rows
    .map((row, i) => {
      const cells = row.slice(0, width).map(q);
      while (cells.length < width) cells.push("''");
      return '    (' + i + ', ' + cells.join(', ') + ')';
    })
    .join(',\n');
}

const projectRows = projects.map((p) => [p[0], p[1], p[2], p[3], p[4]]);
const indexRows = indexEntries.map((e) => [e[0], e[1], e[2], e[3]]);
const galleryRows = gallery.map((g) => [g[0], g[1], g[2]]);

const seed = `/* ============================================================
   PTC — content seed (generated by supabase/generate-seed.js)

   ${projectRows.length} featured projects, ${indexRows.length} project index entries,
   ${galleryRows.length} photographs. Only fills empty tables, so it is safe to
   re-run.
   ============================================================ */

begin;

insert into public.projects (sort_order, category, name, location, image, detail)
select * from (values
${valuesBlock(projectRows, 5)}
) as v(sort_order, category, name, location, image, detail)
where not exists (select 1 from public.projects);

insert into public.index_entries (sort_order, category, name, location, detail)
select * from (values
${valuesBlock(indexRows, 4)}
) as v(sort_order, category, name, location, detail)
where not exists (select 1 from public.index_entries);

insert into public.gallery_photos (sort_order, image, caption, category)
select * from (values
${valuesBlock(galleryRows, 3)}
) as v(sort_order, image, caption, category)
where not exists (select 1 from public.gallery_photos);

commit;
`;

const schema = fs.readFileSync(path.join(__dirname, 'schema.sql'), 'utf8');

fs.writeFileSync(path.join(__dirname, 'seed.sql'), seed);
fs.writeFileSync(
  path.join(__dirname, 'setup.sql'),
  schema.trimEnd() + '\n\n\n' + seed.split('\n').slice(7).join('\n')
);

console.log(
  'seed.sql and setup.sql written — ' +
  projectRows.length + ' projects, ' +
  indexRows.length + ' index entries, ' +
  galleryRows.length + ' photos'
);
