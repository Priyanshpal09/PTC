/* ============================================================
   PTC — Supabase schema

   Three tables hold everything the website and the admin console
   display: the 50 featured projects, the project index and the
   photo gallery.

   Run this once in the Supabase dashboard → SQL Editor
   (or paste supabase/setup.sql, which is this file plus the seed).

   ACCESS MODEL
     - anyone (anon key) may READ the content: it is the same
       content the public website shows
     - only signed-in staff (Supabase Auth) may INSERT, UPDATE or
       DELETE — the admin console signs in with email + password
   ============================================================ */

create table if not exists public.projects (
  id          bigint generated by default as identity primary key,
  sort_order  integer     not null default 0,
  category    text        not null check (category in ('building', 'residential', 'industrial')),
  name        text        not null,
  location    text        not null default '',
  image       text        not null default '',
  detail      text        not null default '',
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create table if not exists public.index_entries (
  id          bigint generated by default as identity primary key,
  sort_order  integer     not null default 0,
  category    text        not null check (category in ('building', 'residential', 'industrial')),
  name        text        not null,
  location    text        not null default '',
  detail      text        not null default '',
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create table if not exists public.gallery_photos (
  id          bigint generated by default as identity primary key,
  sort_order  integer     not null default 0,
  image       text        not null,
  caption     text        not null default '',
  category    text        not null default '',
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create index if not exists projects_sort_order_idx      on public.projects (sort_order);
create index if not exists index_entries_sort_order_idx on public.index_entries (sort_order);
create index if not exists gallery_photos_sort_order_idx on public.gallery_photos (sort_order);

/* ------------------------------------------------------------
   Keep updated_at honest
   ------------------------------------------------------------ */
create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists projects_set_updated_at on public.projects;
create trigger projects_set_updated_at
  before update on public.projects
  for each row execute function public.set_updated_at();

drop trigger if exists index_entries_set_updated_at on public.index_entries;
create trigger index_entries_set_updated_at
  before update on public.index_entries
  for each row execute function public.set_updated_at();

drop trigger if exists gallery_photos_set_updated_at on public.gallery_photos;
create trigger gallery_photos_set_updated_at
  before update on public.gallery_photos
  for each row execute function public.set_updated_at();

/* ------------------------------------------------------------
   Row level security
   ------------------------------------------------------------ */
alter table public.projects      enable row level security;
alter table public.index_entries enable row level security;
alter table public.gallery_photos enable row level security;

grant usage on schema public to anon, authenticated;
grant select on public.projects, public.index_entries, public.gallery_photos to anon, authenticated;
grant insert, update, delete on public.projects, public.index_entries, public.gallery_photos to authenticated;

/* read: open, because this is the website's own content */
drop policy if exists projects_public_read on public.projects;
create policy projects_public_read on public.projects
  for select to anon, authenticated using (true);

drop policy if exists index_entries_public_read on public.index_entries;
create policy index_entries_public_read on public.index_entries
  for select to anon, authenticated using (true);

drop policy if exists gallery_photos_public_read on public.gallery_photos;
create policy gallery_photos_public_read on public.gallery_photos
  for select to anon, authenticated using (true);

/* write: staff only — every authenticated user is staff. If you later
   want to restrict editing to named accounts, replace `to authenticated`
   with a check against auth.jwt() ->> 'email' or a staff table. */
drop policy if exists projects_staff_write on public.projects;
create policy projects_staff_write on public.projects
  for all to authenticated using (true) with check (true);

drop policy if exists index_entries_staff_write on public.index_entries;
create policy index_entries_staff_write on public.index_entries
  for all to authenticated using (true) with check (true);

drop policy if exists gallery_photos_staff_write on public.gallery_photos;
create policy gallery_photos_staff_write on public.gallery_photos
  for all to authenticated using (true) with check (true);
